-- Record the Prima share of wallet escrow releases and collected manual fees
-- so balances can be reconciled against payouts and commissions.

-- Some deployed projects still have the legacy reward_credits field only.
-- New referral payouts are wallet amounts in the gig currency.
ALTER TABLE public.gig_referrals
  ADD COLUMN IF NOT EXISTS reward_amount NUMERIC,
  ADD COLUMN IF NOT EXISTS reward_currency TEXT;

CREATE TABLE IF NOT EXISTS public.platform_revenue_ledger (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source TEXT NOT NULL CHECK (source IN ('wallet_escrow_fee', 'manual_commission_fee')),
  gig_id UUID REFERENCES public.gigs(id) ON DELETE SET NULL,
  application_id UUID REFERENCES public.applications(id) ON DELETE SET NULL,
  commission_id UUID REFERENCES public.commissions(id) ON DELETE SET NULL,
  amount NUMERIC NOT NULL CHECK (amount >= 0),
  currency TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (
    (source = 'wallet_escrow_fee' AND application_id IS NOT NULL AND commission_id IS NULL)
    OR
    (source = 'manual_commission_fee' AND commission_id IS NOT NULL AND application_id IS NULL)
  )
);

CREATE UNIQUE INDEX IF NOT EXISTS platform_revenue_wallet_application_unique
  ON public.platform_revenue_ledger(application_id)
  WHERE application_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS platform_revenue_commission_unique
  ON public.platform_revenue_ledger(commission_id)
  WHERE commission_id IS NOT NULL;

REVOKE ALL ON public.platform_revenue_ledger FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.record_wallet_escrow_platform_fee()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  INSERT INTO public.platform_revenue_ledger
    (source, gig_id, application_id, amount, currency)
  VALUES
    ('wallet_escrow_fee', NEW.gig_id, NEW.application_id,
     ROUND(NEW.amount * 0.10, 2), NEW.currency)
  ON CONFLICT DO NOTHING;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS record_wallet_escrow_platform_fee ON public.gig_application_payouts;
CREATE TRIGGER record_wallet_escrow_platform_fee
  AFTER INSERT ON public.gig_application_payouts
  FOR EACH ROW EXECUTE FUNCTION public.record_wallet_escrow_platform_fee();

CREATE OR REPLACE FUNCTION public.record_manual_commission_platform_fee()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_referral_reward NUMERIC := 0;
  v_platform_fee NUMERIC;
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status AND NEW.status = 'paid' THEN
    SELECT COALESCE(SUM(gr.reward_amount), 0) INTO v_referral_reward
    FROM public.gig_referrals gr
    WHERE gr.gig_id = NEW.gig_id
      AND gr.referred_id = NEW.worker_id
      AND gr.status = 'completed'
      AND gr.reward_given = true;

    v_platform_fee := GREATEST(0, ROUND(NEW.commission_amount - v_referral_reward, 2));
    INSERT INTO public.platform_revenue_ledger
      (source, gig_id, commission_id, amount, currency)
    VALUES
      ('manual_commission_fee', NEW.gig_id, NEW.id, v_platform_fee,
       COALESCE(NULLIF(NEW.currency, ''), 'NGN'))
    ON CONFLICT DO NOTHING;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS record_manual_commission_platform_fee ON public.commissions;
CREATE TRIGGER record_manual_commission_platform_fee
  AFTER UPDATE OF status ON public.commissions
  FOR EACH ROW EXECUTE FUNCTION public.record_manual_commission_platform_fee();

REVOKE ALL ON FUNCTION public.record_wallet_escrow_platform_fee() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.record_manual_commission_platform_fee() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.record_wallet_escrow_platform_fee() TO service_role;
GRANT EXECUTE ON FUNCTION public.record_manual_commission_platform_fee() TO service_role;

-- Populate the ledger for historical rows that already have an exact payout
-- or collected commission record. Unique indexes keep this safe on reruns.
INSERT INTO public.platform_revenue_ledger
  (source, gig_id, application_id, amount, currency)
SELECT 'wallet_escrow_fee', p.gig_id, p.application_id,
       ROUND(p.amount * 0.10, 2), p.currency
FROM public.gig_application_payouts p
ON CONFLICT DO NOTHING;

INSERT INTO public.platform_revenue_ledger
  (source, gig_id, commission_id, amount, currency)
SELECT 'manual_commission_fee', c.gig_id, c.id,
       GREATEST(0, ROUND(c.commission_amount - COALESCE(r.reward_amount, 0), 2)),
       COALESCE(NULLIF(c.currency, ''), 'NGN')
FROM public.commissions c
LEFT JOIN LATERAL (
  SELECT SUM(gr.reward_amount) AS reward_amount
  FROM public.gig_referrals gr
  WHERE gr.gig_id = c.gig_id AND gr.referred_id = c.worker_id
    AND gr.status = 'completed' AND gr.reward_given = true
) r ON true
WHERE c.status = 'paid'
ON CONFLICT DO NOTHING;

-- Reconcile known legacy commission duplicates after confirming the linked
-- Fincra checkout attempts were canceled before payment. Preserve an audit
-- snapshot of every commission row removed or corrected.
BEGIN;

CREATE TABLE IF NOT EXISTS public.commission_reconciliation_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_key TEXT NOT NULL UNIQUE,
  commission_id UUID NOT NULL,
  action TEXT NOT NULL CHECK (action IN ('currency_corrected', 'duplicate_removed')),
  original_record JSONB NOT NULL,
  note TEXT NOT NULL,
  reconciled_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE public.commission_reconciliation_audit ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.commission_reconciliation_audit FROM PUBLIC, anon, authenticated;

DO $$
DECLARE
  v_count INTEGER;
  v_receipt RECORD;
BEGIN
  -- Verify the exact receipt that is the source of truth for Trader Assistant.
  SELECT amount, commission_amount, currency, completed, disputed
    INTO v_receipt
  FROM public.receipts
  WHERE id = '00280d58-9b5f-47d3-8604-583f2558c172'::UUID
    AND gig_id = 'e2f55b8a-74eb-45fd-a1fd-b2e20ee2e13c'::UUID
    AND worker_id = '31c081a9-27fe-43fd-9b04-bedc3870a452'::UUID;
  IF NOT FOUND OR v_receipt.amount <> 30000
     OR v_receipt.commission_amount <> 3000
     OR UPPER(v_receipt.currency) <> 'NGN'
     OR NOT v_receipt.completed OR v_receipt.disputed THEN
    RAISE EXCEPTION 'Trader Assistant receipt no longer matches the reviewed NGN 30,000 / NGN 3,000 record; stop and inspect before reconciling';
  END IF;

  -- The user confirmed all five checkouts tied to this commission were
  -- canceled before paying. Require exactly those five, all still pending or
  -- already marked failed, and none completed before changing their status.
  SELECT count(*) INTO v_count
  FROM public.wallet_transactions
  WHERE related_commission_id = '8343d2ba-674d-4d74-a7c6-ef0ff81cfdb4'::UUID;
  IF v_count <> 5 OR EXISTS (
    SELECT 1 FROM public.wallet_transactions
    WHERE related_commission_id = '8343d2ba-674d-4d74-a7c6-ef0ff81cfdb4'::UUID
      AND (type <> 'fund_in' OR status NOT IN ('pending', 'failed')
           OR amount <> 3000 OR UPPER(currency) <> 'USD')
  ) THEN
    RAISE EXCEPTION 'Trader Assistant Fincra attempt records changed; inspect them before reconciling';
  END IF;

  IF NOT EXISTS (
       SELECT 1 FROM public.commissions
       WHERE id = '8343d2ba-674d-4d74-a7c6-ef0ff81cfdb4'::UUID
         AND gig_id = 'e2f55b8a-74eb-45fd-a1fd-b2e20ee2e13c'::UUID
         AND worker_id = '31c081a9-27fe-43fd-9b04-bedc3870a452'::UUID
         AND status = 'pending' AND gig_amount = 30000
         AND commission_amount = 3000 AND UPPER(currency) IN ('USD', 'NGN')
     ) OR EXISTS (
       SELECT 1 FROM public.commissions
       WHERE id = 'afed16fa-928f-4b55-8ee1-4345936c6d4f'::UUID
         AND (gig_id <> 'e2f55b8a-74eb-45fd-a1fd-b2e20ee2e13c'::UUID
              OR worker_id <> '31c081a9-27fe-43fd-9b04-bedc3870a452'::UUID
              OR status <> 'pending' OR gig_amount <> 30000
              OR commission_amount <> 3000 OR UPPER(currency) <> 'USD')
     ) THEN
    RAISE EXCEPTION 'Trader Assistant commission rows changed; inspect before reconciling';
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.wallet_transactions
    WHERE related_commission_id = 'afed16fa-928f-4b55-8ee1-4345936c6d4f'::UUID
  ) THEN
    RAISE EXCEPTION 'The duplicate Trader Assistant commission has linked transactions; inspect before removal';
  END IF;

  IF NOT EXISTS (
       SELECT 1 FROM public.commissions
       WHERE id = 'fad1e065-ce54-4bae-aff7-76c00517ce70'::UUID
         AND gig_id = 'd1c384bd-439e-4bdb-a8f4-edb7f4a67da8'::UUID
         AND worker_id = '31c081a9-27fe-43fd-9b04-bedc3870a452'::UUID
         AND status = 'paid' AND currency = 'NGN' AND commission_amount = 500
     ) OR EXISTS (
       SELECT 1 FROM public.commissions
       WHERE id = 'fc38875c-3f4b-4370-b0d6-c1f91e443b3d'::UUID
         AND (gig_id <> 'd1c384bd-439e-4bdb-a8f4-edb7f4a67da8'::UUID
              OR worker_id <> '31c081a9-27fe-43fd-9b04-bedc3870a452'::UUID
              OR status <> 'pending' OR currency <> 'NGN'
              OR commission_amount <> 500 OR gig_amount <> 2000)
     ) THEN
    RAISE EXCEPTION 'Electrician commission rows changed; inspect before cleanup';
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.wallet_transactions
    WHERE related_commission_id = 'fc38875c-3f4b-4370-b0d6-c1f91e443b3d'::UUID
       OR (gig_id = 'd1c384bd-439e-4bdb-a8f4-edb7f4a67da8'::UUID
           AND user_id = '31c081a9-27fe-43fd-9b04-bedc3870a452'::UUID
           AND type = 'commission_payment')
  ) THEN
    RAISE EXCEPTION 'A wallet payment is linked to the pending Electrician commission; inspect before cleanup';
  END IF;
END;
$$;

-- Correct the surviving commission from the completed receipt and preserve
-- its pre-correction state in an audit table.
INSERT INTO public.commission_reconciliation_audit
  (event_key, commission_id, action, original_record, note)
SELECT 'currency_corrected:8343d2ba-674d-4d74-a7c6-ef0ff81cfdb4', c.id,
       'currency_corrected', to_jsonb(c),
       'Corrected from the completed receipt after user confirmed all linked Fincra checkouts were canceled before payment.'
FROM public.commissions c
WHERE c.id = '8343d2ba-674d-4d74-a7c6-ef0ff81cfdb4'::UUID
  AND (UPPER(COALESCE(c.currency, '')) <> 'NGN'
       OR c.gig_amount <> 30000 OR c.commission_amount <> 3000)
ON CONFLICT (event_key) DO NOTHING;

UPDATE public.wallet_transactions
SET status = 'failed',
    description = concat_ws(' | ', NULLIF(description, ''),
      'Canceled by user before payment; closed during commission reconciliation 2026-10-23')
WHERE related_commission_id = '8343d2ba-674d-4d74-a7c6-ef0ff81cfdb4'::UUID
  AND status = 'pending';

UPDATE public.commissions
SET gig_amount = 30000,
    commission_amount = 3000,
    currency = 'NGN'
WHERE id = '8343d2ba-674d-4d74-a7c6-ef0ff81cfdb4'::UUID
  AND status = 'pending';

-- Remove only the known unpaid duplicates. Keep an audit snapshot first.
INSERT INTO public.commission_reconciliation_audit
  (event_key, commission_id, action, original_record, note)
SELECT 'duplicate_removed:' || c.id::TEXT, c.id, 'duplicate_removed', to_jsonb(c),
       'Duplicate pending commission for a gig/worker pair; no Fincra or wallet payment transaction referenced this row.'
FROM public.commissions c
WHERE c.id IN (
  'afed16fa-928f-4b55-8ee1-4345936c6d4f'::UUID,
  'fc38875c-3f4b-4370-b0d6-c1f91e443b3d'::UUID
)
ON CONFLICT (event_key) DO NOTHING;

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM public.wallet_transactions
    WHERE related_commission_id IN (
      'afed16fa-928f-4b55-8ee1-4345936c6d4f'::UUID,
      'fc38875c-3f4b-4370-b0d6-c1f91e443b3d'::UUID
    )
  ) THEN
    RAISE EXCEPTION 'A duplicate commission has a linked wallet/Fincra transaction; inspect it instead of removing the row';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.commissions
    WHERE id = 'fad1e065-ce54-4bae-aff7-76c00517ce70'::UUID
      AND status = 'paid' AND currency = 'NGN' AND commission_amount = 500
  ) THEN
    RAISE EXCEPTION 'The paid Electrician commission is not as reviewed; stop and inspect before cleanup';
  END IF;

  DELETE FROM public.commissions
  WHERE id IN (
    'afed16fa-928f-4b55-8ee1-4345936c6d4f'::UUID,
    'fc38875c-3f4b-4370-b0d6-c1f91e443b3d'::UUID
  ) AND status = 'pending';

  IF EXISTS (
    SELECT 1 FROM public.commissions
    GROUP BY gig_id, worker_id
    HAVING gig_id IS NOT NULL AND worker_id IS NOT NULL AND count(*) > 1
  ) THEN
    RAISE EXCEPTION 'Other duplicate commission pairs exist; do not add the unique index until they are reviewed';
  END IF;
END;
$$;

CREATE UNIQUE INDEX IF NOT EXISTS commissions_gig_worker_unique
  ON public.commissions(gig_id, worker_id)
  WHERE gig_id IS NOT NULL AND worker_id IS NOT NULL;

COMMIT;
